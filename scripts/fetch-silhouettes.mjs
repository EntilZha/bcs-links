// Vendors bird silhouettes from PhyloPic (https://www.phylopic.org) into
// src/components/silhouettes.ts, so the site never calls PhyloPic at runtime.
//
// Only public-domain (CC0 / PD mark) or CC BY images are allowed: NC and SA licences are
// refused below rather than trusted to a reviewer. CC BY images need the credit that the
// footer renders from SILHOUETTE_CREDITS.
//
// Run with `pixi run silhouettes`, then review the diff.
import fs from "node:fs";

const BUILD = 557; // PhyloPic data build the ids below were chosen from
// key: [PhyloPic image uuid, what we call it on the page]. Where the silhouette is of a
// close relative (same shape, different species), the note says so and the credits show it.
const PICKS = {
  eagle: ["80064052-3255-4b19-9125-5a0c79dec5bf", "Bald Eagle"],
  heron: ["ef8228ef-8738-4110-927c-3ab6b9c03b0e", "Great Blue Heron"],
  // In flight, for the faint birds crossing the header.
  osprey: ["d25f13d6-722e-4da3-8073-0a86b8a15976", "Osprey"],
  goose: ["7c3654ef-65f9-4a63-a879-4d48e8268831", "Canada Goose"],
  crow: ["10fa9256-0c25-4513-9f92-2707daff0d5e", "American Crow"],
  swallow: ["26c55043-54c5-4d88-9478-1f2073fe5e71", "Barn Swallow"],
  robin: ["7be55586-e993-4eb3-88a0-9ec7a2ba0c7d", "American Robin"],
  // No Anna's in a usable pose on PhyloPic; hummingbird outlines barely differ by species.
  hummingbird: ["618b6a9d-6aa6-4316-bf25-2a7a3f788e88", "Anna's Hummingbird (outline of a Ruby-throated)"],
  owl: ["5672d2a9-8f5f-449c-a6dd-ba4ebe3f768b", "Barn Owl"],
  // Drawn with its own black-and-white pattern (the white parts are cut-outs).
  downy: ["03a72ae8-3114-43b0-98c9-c372f76b29a0", "Downy Woodpecker"],
};
const ALLOWED = /creativecommons\.org\/(publicdomain\/(zero|mark)\/1\.0|licenses\/by\/\d\.\d)\/?$/;

const out = {};
for (const [key, [uuid, name]] of Object.entries(PICKS)) {
  const meta = await (await fetch(`https://api.phylopic.org/images/${uuid}?build=${BUILD}`)).json();
  const license = meta._links.license.href;
  if (!ALLOWED.test(license)) throw new Error(`${key}: licence ${license} is not allowed`);
  const raw = await (await fetch(meta._links.vectorFile.href)).text();

  const viewBox = raw.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number).map((n) => +n.toFixed(2)).join(" ");
  // Keep the drawing, drop the prolog/metadata, and let CSS pick the colour.
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<metadata>[\s\S]*?<\/metadata>/, "")
    .replace(/fill="#000000"/g, 'fill="currentColor"')
    .replace(/\s+/g, " ")
    .trim();

  out[key] = {
    name,
    viewBox,
    inner,
    species: meta._links.specificNode?.title ?? "",
    license,
    attribution: meta.attribution ?? null,
    source: `https://www.phylopic.org/images/${uuid}`,
  };
  console.log(`${key}: ${out[key].species} — ${license} — ${out[key].attribution ?? "no attribution"}`);
}

const ts = `// GENERATED by scripts/fetch-silhouettes.mjs from PhyloPic — do not edit by hand.
export type SilhouetteId = ${Object.keys(out).map((k) => JSON.stringify(k)).join(" | ")};

export interface Silhouette {
  /** what the page calls this bird */
  name: string;
  viewBox: string;
  inner: string;
  species: string;
  license: string;
  attribution: string | null;
  source: string;
}

export const SILHOUETTES: Record<SilhouetteId, Silhouette> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(new URL("../src/components/silhouettes.ts", import.meta.url), ts);
